// Run after smoke-motion.js in the same browser session. No real API writes.
async (page) => {
  const base = new URL(page.url()).origin;
  await page.unroute('**/api/auth/me');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const response = page.waitForResponse(r => new URL(r.url()).pathname === '/api/tasks');
  await page.goto(base+'/dashboard');
  const tasks = await (await response).json();
  tasks[0] = { ...tasks[0], isCompleted: true, completedAt: Math.floor(Date.now()/1000) };
  tasks[1] = { ...tasks[1], isCompleted: true, completedAt: Math.floor(Date.now()/1000), claimedByWorkerId: 2, claimedByName: 'Сергей' };
  tasks[2].title = 'Проверить ценники и соответствие ассортимента перед началом вечерней смены';
  await page.route('**/api/tasks', route => route.fulfill({ json: tasks }));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload();
  await page.getByRole('heading',{ name:'Задачи', exact:true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.stat-tile-value')?.textContent === '4');
  const progress = page.getByRole('progressbar',{ name:'Выполнено задач' });
  check(await progress.getAttribute('aria-valuenow') === '2', 'Shift progress ignores tasks completed by colleagues');
  check(await progress.getAttribute('aria-valuemax') === '6', 'Shift total changed');
  await page.locator('.worker-section-header').first().click();
  const task = page.getByRole('button',{ name:tasks[2].title, exact:true });
  await task.waitFor();
  check(await page.locator('.group-year-header').count() === 0, 'Current month adds redundant archive headings');
  await page.screenshot({ path:'output/playwright/workspace-desktop.png', fullPage:true });
  await task.focus();
  await page.keyboard.press('Enter');
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state:'hidden' });
  check(await task.evaluate(el=>el === document.activeElement),'Task keyboard focus was not restored');
  const search = page.getByRole('textbox',{ name:'Поиск задач' });
  await search.fill('нет-такой-задачи');
  await page.getByRole('heading',{ name:'Ничего не нашлось' }).waitFor();
  await page.screenshot({ path:'output/playwright/workspace-empty-search.png' });
  await page.getByRole('button',{ name:'Сбросить фильтры', exact:true }).click();
  check(await search.inputValue() === '', 'Search reset failed');
  await progress.waitFor();
  const photo = page.getByRole('button',{ name:'С фото', exact:true });
  await photo.click();
  check(await photo.getAttribute('aria-pressed') === 'true','Filter state is not announced');
  await page.getByRole('button',{ name:'Сбросить фильтры', exact:true }).click();
  check(await photo.getAttribute('aria-pressed') === 'false','Filter reset failed');
  await page.getByRole('button',{ name:'Создать задачу', exact:true }).click();
  await page.waitForURL('**/tasks/new');
  await page.locator('[data-page-skeleton]:visible').waitFor({ state:'hidden' });
  for (const width of [360,390]) {
    await page.setViewportSize({ width, height:844 });
    await page.goto(base+'/dashboard');
    await progress.waitFor();
    await page.locator('.worker-section-header').first().click();
    await task.waitFor();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth+1 || document.querySelector('#root').scrollWidth > innerWidth+1);
    check(!overflow, 'Mobile horizontal overflow at '+width);
    const actions = page.locator('.task-actions').first();
    check(await actions.getByRole('button').count() === 3,'Mobile task actions disappeared');
    await page.locator('#root').evaluate(el=>{el.scrollTop=0;});
    await page.screenshot({ path:`output/playwright/workspace-mobile-${width}.png` });
    await task.scrollIntoViewIfNeeded();
    await page.screenshot({ path:`output/playwright/workspace-mobile-tasks-${width}.png` });
  }
  await page.getByRole('button',{ name:'Меню', exact:true }).click();
  await page.getByRole('radio',{ name:'Тёмная', exact:true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state:'hidden' });
  await page.screenshot({ path:'output/playwright/workspace-mobile-dark.png' });
  check(errors.length===0, errors.join('; '));
  return { checks:'shift counters, keyboard task opening, empty search, filter reset, desktop create action, 360/390px, dark theme', errors };
}
