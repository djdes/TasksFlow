/**
 * Тесты normalizePhone — мягкая нормализация телефонов.
 *
 * Контекст: server/phone-normalize.ts с явным предупреждением
 * "Расширять до strict-normalization безопасно ТОЛЬКО после миграции
 * существующих users.phone строк, иначе lookup перестанет находить
 * юзеров заведённых до миграции".
 *
 * Эти тесты ЗАМОРАЖИВАЮТ текущее поведение. Если кто-то добавит
 * `replace(/\D/g, "")` без миграции БД — упадёт пара тестов и
 * напомнит: «нужна миграция users.phone сначала».
 *
 * Текущее поведение: убирает только пробелы и дефисы. Скобки и
 * точки — НЕ убирает (разные форматы записи остаются разными).
 */

import { describe, it, expect } from "vitest";
import { normalizePhone } from "../server/phone-normalize";

describe("normalizePhone — текущее поведение (мягкое)", () => {
  it("убирает пробелы", () => {
    expect(normalizePhone("+7 999 123 45 67")).toBe("+79991234567");
  });

  it("убирает дефисы", () => {
    expect(normalizePhone("+7-999-123-45-67")).toBe("+79991234567");
  });

  it("убирает смесь пробелов и дефисов", () => {
    expect(normalizePhone("+7 999-123 45-67")).toBe("+79991234567");
  });

  it("убирает табуляции и переносы (\\s+)", () => {
    expect(normalizePhone("+7\t999\n123 4567")).toBe("+79991234567");
  });

  it("оставляет уже нормализованный номер без изменений", () => {
    expect(normalizePhone("+79991234567")).toBe("+79991234567");
  });

  it("возвращает пустую строку для пустого input'а", () => {
    expect(normalizePhone("")).toBe("");
  });
});

describe("normalizePhone — НЕ убирает другие символы (zhamerz freeze)", () => {
  // ЯВНО документируем: текущая нормализация НЕ страйп'ает скобки и
  // точки. Если эти тесты упадут — кто-то расширил normalize, и БЕЗ
  // миграции users.phone это сломает lookup для уже-зарегистрированных
  // юзеров. См. комментарий в server/phone-normalize.ts.

  it("СОХРАНЯЕТ скобки (известный edge case)", () => {
    expect(normalizePhone("+7(999)1234567")).toBe("+7(999)1234567");
  });

  it("СОХРАНЯЕТ точки", () => {
    expect(normalizePhone("+7.999.123.4567")).toBe("+7.999.123.4567");
  });

  it("СОХРАНЯЕТ скобки даже после удаления пробелов", () => {
    expect(normalizePhone("+7 (999) 123 45 67")).toBe("+7(999)1234567");
  });

  it("разные форматы дают РАЗНЫЕ нормализованные значения", () => {
    // Это и есть «мягкое» поведение: один человек может быть в БД
    // несколько раз с +7(999)1234567 и +79991234567. См. отложенная
    // миграция в комментарии phone-normalize.ts.
    expect(normalizePhone("+7(999)1234567")).not.toBe(
      normalizePhone("+79991234567"),
    );
  });
});
