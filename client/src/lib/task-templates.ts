/**
 * Готовые наборы задач на смену по отраслям — быстрый старт для новой
 * компании: админ выбирает отрасль, снимает лишние галочки и создаёт
 * задачи пачкой (TaskTemplatesDialog). Данные статичные, без сервера.
 *
 * weekDays: null — каждый день (так же хранятся задачи из формы без
 * выбранных дней), иначе 0=Вс … 6=Сб, как в tasks.weekDays.
 */

export type TaskTemplate = {
  title: string;
  category: string;
  requiresPhoto: boolean;
  weekDays: number[] | null;
  /** Одна строка: что именно сделать и как понять, что готово. */
  description: string;
};

export type TaskTemplateIndustryId =
  | "cleaning"
  | "food"
  | "retail"
  | "service"
  | "logistics"
  | "security"
  | "manufacturing";

export type TaskTemplateIndustry = {
  id: TaskTemplateIndustryId;
  name: string;
  tasks: TaskTemplate[];
};

const WEEKDAYS = [1, 2, 3, 4, 5];

function task(
  title: string,
  category: string,
  description: string,
  options: { photo?: boolean; days?: number[] } = {},
): TaskTemplate {
  return {
    title,
    category,
    description,
    requiresPhoto: options.photo ?? false,
    weekDays: options.days ?? null,
  };
}

