export function getTaskTemplateIndustry(id: TaskTemplateIndustryId | string): TaskTemplateIndustry | undefined {
  return TASK_TEMPLATE_INDUSTRIES.find((industry) => industry.id === id);
}

/**
 * Тело POST /api/tasks для задачи из шаблона. Повторяющаяся, без срока
 * и премии — админ поправит цену и расписание обычным редактированием.
 */
export function templateTaskPayload(template: TaskTemplate, workerId: number) {
  return {
    title: template.title,
    workerId,
    requiresPhoto: template.requiresPhoto,
    weekDays: template.weekDays,
    monthDay: null,
    dueDate: null,
    isRecurring: true,
    price: 0,
    category: template.category,
    description: template.description,
    checklist: null,
  };
}

export type TemplateTaskFailure = { template: TaskTemplate; message: string };

/**
 * Создаёт задачи по одной: сбой одной не останавливает остальные, а
 * причина остаётся рядом с её названием, чтобы показать её в списке.
 * Последовательно, а не Promise.all: задачи ложатся в список в порядке
 * шаблона, а прогресс «k из N» соответствует реально созданным.
 */
export async function createTemplateTasks(
  templates: readonly TaskTemplate[],
  workerId: number,
  post: (payload: ReturnType<typeof templateTaskPayload>) => Promise<unknown>,
  onProgress?: (done: number, total: number) => void,
): Promise<{ created: number; failures: TemplateTaskFailure[] }> {
  let created = 0;
  const failures: TemplateTaskFailure[] = [];
  for (let i = 0; i < templates.length; i++) {
    const template = templates[i];
    try {
      await post(templateTaskPayload(template, workerId));
      created += 1;
    } catch (err) {
      const message = err instanceof Error && err.message ? err.message : "Не удалось создать задачу";
      failures.push({ template, message });
    }
    onProgress?.(i + 1, templates.length);
  }
  return { created, failures };
}
