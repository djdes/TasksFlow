const DOW_NAMES = ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"];

export function buildJobDescriptionInput(params: {
  employeeName: string;
  position: string | null;
  today: string;
  dow: number;
  categories: string[];
  text: string;
}): string {
  const categories = params.categories.length > 0
    ? params.categories.map((c) => `- ${c}`).join("\n")
    : "(категорий пока нет)";
  return [
    `Сотрудник: ${params.employeeName}`,
    `Должность: ${params.position?.trim() || "не указана"}`,
    `Сегодня: ${params.today} (${DOW_NAMES[params.dow] ?? ""})`,
    "",
    "Категории задач компании:",
    categories,
    "",
    "Должностная инструкция:",
    "<<<",
    params.text,
    ">>>",
  ].join("\n");
}
