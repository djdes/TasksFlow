const DOW_NAMES = ["воскресенье", "понедельник", "вторник", "среда", "четверг", "пятница", "суббота"];

export function buildJobDescriptionInput(params: {
  employeeName: string;
  position: string | null;
  today: string;
  dow: number;
  categories: string[];
  text: string;
  /** Инструкции нет — задачи подбираются по названию должности (правило 14). */
  byPosition?: boolean;
}): string {
  const categories = params.categories.length > 0
    ? params.categories.map((c) => `- ${c}`).join("\n")
    : "(категорий пока нет)";
  const head = [
    `Сотрудник: ${params.employeeName}`,
    `Должность: ${params.position?.trim() || "не указана"}`,
    `Сегодня: ${params.today} (${DOW_NAMES[params.dow] ?? ""})`,
    "",
    "Категории задач компании:",
    categories,
    "",
  ];
  if (params.byPosition) {
    return [
      ...head,
      "Режим «по должности»: должностной инструкции нет. Подбери типовые задачи для должности:",
      "<<<",
      params.text,
      ">>>",
    ].join("\n");
  }
  return [...head, "Должностная инструкция:", "<<<", params.text, ">>>"].join("\n");
}
